"""Read-only FreeCAD inventory: sketch DoF + stored geometry + 1.1.x recompute preview.

Run with FreeCAD's command-line interpreter (FreeCAD is an AppImage here):
    <freecadcmd> scripts/cad_inventory_fc.py
e.g. /tmp/.mount_FreeCA*/usr/bin/freecadcmd scripts/cad_inventory_fc.py

Every .FCStd is first COPIED to a temporary directory; only the copies are opened,
solved and recomputed. Nothing is saved. Writes:
    docs/inventory/sketch_dof.md
    docs/inventory/geometry.md
    docs/inventory/fc_data.json
"""
import json
import os
import pathlib
import shutil
import tempfile

import FreeCAD

REPO = pathlib.Path(os.environ.get("LYSKAMM_REPO", "/home/lorenzo/projects/lyskamm"))
OUT = REPO / "docs" / "inventory"
TOL = 1e-6


def r(x, n=3):
    return round(float(x), n)


def bb(b):
    return [r(b.XMin), r(b.YMin), r(b.ZMin), r(b.XMax), r(b.YMax), r(b.ZMax)]


def shape_info(s):
    if s is None or s.isNull():
        return None
    info = {"volume": r(s.Volume, 2), "bbox": bb(s.BoundBox), "valid": s.isValid(),
            "solids": len(s.Solids)}
    try:
        info["com"] = [r(c) for c in s.CenterOfMass] if s.Solids else None
    except Exception:
        info["com"] = None
    dia = set()
    for f in s.Faces:
        surf = f.Surface
        if surf.__class__.__name__ == "Cylinder":
            dia.add(r(2 * surf.Radius, 3))
    info["cyl_diameters"] = sorted(dia)
    return info


def bodies(doc):
    out = []
    for o in doc.Objects:
        if o.TypeId in ("PartDesign::Body", "App::Part"):
            out.append(o)
    if not out:  # e.g. assembly or loose Part::Feature
        out = [o for o in doc.Objects if hasattr(o, "Shape") and o.TypeId.startswith("Part::")
               and not o.InList]
    return out


def main():
    files = sorted(p for p in REPO.rglob("*.FCStd") if ".git" not in p.parts)
    tmp = pathlib.Path(tempfile.mkdtemp(prefix="lyskamm_inv_"))
    data = []
    for src in files:
        rel = str(src.relative_to(REPO))
        dst = tmp / rel.replace("/", "__")
        shutil.copy2(src, dst)
        rec = {"file": rel, "sketches": [], "bodies": [], "recompute_errors": [], "load_errors": []}
        doc = FreeCAD.openDocument(str(dst))
        # objects whose Python proxy did not load (missing addon)
        for o in doc.Objects:
            if hasattr(o, "Proxy") and o.TypeId.endswith("Python"):
                if o.Proxy is None:
                    rec["load_errors"].append(f"{o.Name}: Python proxy not loaded ({o.TypeId})")
        # stored geometry (as saved by FreeCAD 1.0) — this is the baseline
        bl = bodies(doc)
        for b in bl:
            rec["bodies"].append({"name": b.Name, "label": b.Label,
                                  "stored": shape_info(b.Shape)})
        # sketches
        for o in doc.Objects:
            if o.TypeId == "Sketcher::SketchObject":
                res = o.solve()
                rec["sketches"].append({
                    "name": o.Name, "label": o.Label, "solve": res,
                    "dof": getattr(o, "DoF", None),
                    "fully": bool(o.FullyConstrained),
                    "conflicting": list(o.ConflictingConstraints),
                    "redundant": list(o.RedundantConstraints),
                    "partially_redundant": list(o.PartiallyRedundantConstraints),
                    "malformed": list(o.MalformedConstraints),
                    "geo": o.GeometryCount if hasattr(o, "GeometryCount") else len(o.Geometry),
                })
        # recompute preview in this FreeCAD version (on the copy only)
        try:
            doc.recompute()
        except Exception as e:
            rec["recompute_errors"].append(f"recompute raised: {e}")
        for o in doc.Objects:
            st = [s for s in o.State if s in ("Invalid", "Error")]
            if st:
                rec["recompute_errors"].append(f"{o.Name} ({o.Label}): {', '.join(st)}")
        for i, b in enumerate(bl):
            rec["bodies"][i]["recomputed"] = shape_info(b.Shape)
        FreeCAD.closeDocument(doc.Name)  # never saved
        data.append(rec)
        print("done", rel)
    shutil.rmtree(tmp, ignore_errors=True)
    write(data)


def same(a, b):
    if a is None or b is None:
        return a is b
    return abs(a["volume"] - b["volume"]) <= max(TOL, 1e-6 * abs(a["volume"])) and all(
        abs(x - y) < 1e-3 for x, y in zip(a["bbox"], b["bbox"]))


def write(data):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "fc_data.json").write_text(json.dumps(data, indent=1))
    # sketch DoF
    L = ["# Sketch DoF check", "",
         "Generated by `scripts/cad_inventory_fc.py` (FreeCAD solve on temporary copies; nothing saved).",
         "Only sketches with problems are listed. DoF > 0 = under-constrained.", "",
         "| File | Sketch | Geo | DoF | Conflicting | Redundant | Malformed | Note |",
         "|---|---|---|---|---|---|---|---|"]
    n = nbad = 0
    for rec in data:
        for s in rec["sketches"]:
            n += 1
            problems = s["dof"] not in (0, None) or s["conflicting"] or s["redundant"] or s["malformed"] \
                or s["partially_redundant"] or s["geo"] == 0 or s["solve"] != 0
            if not problems:
                continue
            nbad += 1
            note = "empty" if s["geo"] == 0 else ("solve failed" if s["solve"] != 0 else "")
            L.append(f"| `{rec['file']}` | {s['label']} | {s['geo']} | {s['dof']} | {s['conflicting'] or ''} | "
                     f"{(s['redundant'] or []) + (s['partially_redundant'] or []) or ''} | {s['malformed'] or ''} | {note} |")
    L.insert(4, f"**{nbad} of {n} sketches have issues.**\n")
    (OUT / "sketch_dof.md").write_text("\n".join(L) + "\n")
    # geometry
    G = ["# Geometry baseline", "",
         "Generated by `scripts/cad_inventory_fc.py`. *Stored* = shape saved in the file (FreeCAD 1.0) — the",
         "baseline that parametrization must preserve. *Recomputed* = same file recomputed in the current",
         "FreeCAD on a temporary copy (preview of PLAN step 3.0). Units: mm, mm³.", "",
         "| File | Body | Volume (stored) | BBox [xmin,ymin,zmin,xmax,ymax,zmax] | CoM | Recompute in current FreeCAD |",
         "|---|---|---|---|---|---|"]
    for rec in data:
        for b in rec["bodies"]:
            st, rc = b["stored"], b.get("recomputed")
            if st is None:
                G.append(f"| `{rec['file']}` | {b['label']} | — | — | — | {'no shape' if rc is None else 'shape after recompute'} |")
                continue
            verdict = "identical" if same(st, rc) else (
                "**no shape**" if rc is None else f"**differs**: vol {rc['volume']}, bbox {rc['bbox']}")
            if rec["load_errors"]:
                verdict += " ⚠ not meaningful: Python features not loaded (addon missing), so not re-executed"
            elif rec["recompute_errors"]:
                verdict += " ⚠ but features fail to recompute (see list below): shape is the last valid one"
            G.append(f"| `{rec['file']}` | {b['label']} | {st['volume']} | {st['bbox']} | {st['com']} | {verdict} |")
    G += ["", "## Cylindrical-face diameters (stored shape)", "",
          "Raw list of diameters of cylindrical faces — input for the shared-dimension analysis.", ""]
    for rec in data:
        for b in rec["bodies"]:
            if b["stored"] and b["stored"]["cyl_diameters"]:
                G.append(f"- `{rec['file']}` / {b['label']}: {', '.join(map(str, b['stored']['cyl_diameters']))}")
    G += ["", "## Load / recompute problems in current FreeCAD (copies)", ""]
    any_ = False
    for rec in data:
        if rec["load_errors"]:
            names = [e.split(":")[0] for e in rec["load_errors"]]
            G.append(f"- `{rec['file']}`: {len(names)} Python objects not loaded "
                     f"(addon missing): {', '.join(names[:6])}{' …' if len(names) > 6 else ''}")
            any_ = True
        for e in rec["recompute_errors"]:
            G.append(f"- `{rec['file']}`: {e}")
            any_ = True
    if not any_:
        G.append("- none")
    (OUT / "geometry.md").write_text("\n".join(G) + "\n")


main()
