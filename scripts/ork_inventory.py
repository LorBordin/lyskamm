#!/usr/bin/env python3
"""Read-only inventory of the OpenRocket design (lyskamm.ork) -> docs/inventory/openrocket.md

Usage: python3 scripts/ork_inventory.py [path/to/file.ork]
Lengths are converted to mm, masses to g. Never writes to the .ork.
"""
import pathlib
import sys
import xml.etree.ElementTree as ET
import zipfile

REPO = pathlib.Path(__file__).resolve().parent.parent
ORK = REPO / "lyskamm.ork"
OUT = REPO / "docs" / "inventory" / "openrocket.md"

AXIAL = {"nosecone", "bodytube", "transition"}  # components laid out along the axis
LEN_KEYS = ["length", "thickness", "radius", "aftradius", "foreradius", "aftshoulderradius",
            "aftshoulderlength", "foreshoulderradius", "foreshoulderlength", "rootchord", "tipchord",
            "sweeplength", "height", "outerradius", "innerradius", "diameter", "packedlength",
            "packedradius", "radialposition"]


def mm(v):
    v = v.strip()
    auto = v.startswith("auto")
    num = float(v.split()[-1])
    s = f"{num * 1000:.2f}".rstrip("0").rstrip(".")
    return f"{s} (auto)" if auto else s


def load(path):
    with zipfile.ZipFile(path) as z:
        name = next(n for n in z.namelist() if n.endswith(".ork"))
        return ET.fromstring(z.read(name))


def comp_rows(el, depth, rows, pos_mm, parent):
    for c in el:
        tag = c.tag
        name = c.findtext("name") or tag
        props = {}
        for k in LEN_KEYS:
            t = c.findtext(k)
            if t is not None:
                props[k] = mm(t)
        for k in ("shape", "shapeparameter", "fincount", "crosssection", "cant", "instancecount"):
            t = c.findtext(k)
            if t is not None:
                props[k] = t
        mat = c.find("material")
        material = f"{mat.text} ({mat.get('density')} kg/m³)" if mat is not None else ""
        for k in ("overridemass", "overridecg", "overridecd"):
            t = c.findtext(k)
            if t is not None:
                props[k] = t
        pts = c.find("finpoints")
        if pts is not None:
            props["finpoints"] = " ".join(f"({float(p.get('x'))*1000:g},{float(p.get('y'))*1000:g})"
                                          for p in pts.findall("point"))
        position = c.find("axialoffset")
        rel = f"{position.get('method')} {float(position.text)*1000:g}" if position is not None else ""
        start = ""
        if tag in AXIAL and depth == 0:
            start = f"{pos_mm[0]:g}"
            pos_mm[0] += float(c.findtext("length")) * 1000
        rows.append((depth, tag, name, start, rel, material, props))
        sub = c.find("subcomponents")
        if sub is not None:
            comp_rows(sub, depth + 1, rows, pos_mm, name)


def main():
    path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ORK
    root = load(path)
    rocket = root.find("rocket")
    L = ["# OpenRocket inventory", "",
         f"Generated by `scripts/ork_inventory.py` from `{path.name}` "
         f"(creator: {root.get('creator')}, format {root.get('version')}). Lengths in mm.", ""]
    stages = rocket.findall("subcomponents/stage")
    L.append(f"- Rocket: **{rocket.findtext('name')}**, stages: {len(stages)}")
    total = 0.0
    for st in stages:
        rows, pos = [], [0.0]
        comp_rows(st.find("subcomponents"), 0, rows, pos, st.findtext("name"))
        total += pos[0]
        L += ["", f"## Stage: {st.findtext('name')} — axial length {pos[0]:g} mm", "",
              "| # | Component | Type | Starts at (from nose tip) | Relative position | Material | Dimensions / properties |",
              "|---|---|---|---|---|---|---|"]
        for i, (d, tag, name, start, rel, mat, props) in enumerate(rows, 1):
            pv = "; ".join(f"{k}={v}" for k, v in props.items())
            L.append(f"| {i} | {'↳ ' * d}{name} | {tag} | {start} | {rel} | {mat} | {pv} |")
    L += ["", f"**Total length: {total:g} mm**", ""]
    # checks
    alltags = {e.tag for e in rocket.iter()}
    sims = root.findall("simulations/simulation")
    checks = [
        ("motor mount / inner tube", "innertube" in alltags),
        ("motor configuration", "motorconfiguration" in alltags or "motor" in alltags),
        ("recovery device (parachute/streamer)", bool({"parachute", "streamer"} & alltags)),
        ("mass components / mass overrides", bool({"masscomponent", "overridemass"} & alltags)),
        ("launch lug / rail button", bool({"launchlug", "railbutton"} & alltags)),
        ("simulations", bool(sims)),
    ]
    L += ["## Completeness checks", ""] + [f"- {'✅' if ok else '❌ missing'}: {what}" for what, ok in checks]
    mats = sorted({m.text for m in rocket.iter("material")})
    L += ["", f"- Materials used: {', '.join(mats)}"]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
